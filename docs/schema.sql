create table usuarios (
  id        bigint generated by default as identity primary key,
  username  varchar(255) not null unique,
  senha     varchar(255) not null,
  papel     varchar(20)  not null default 'CLIENTE'
            check (papel in ('CLIENTE','EMPRESA','BANCO'))
);

create table clientes (
  id         bigint generated by default as identity primary key,
  usuario_id bigint unique references usuarios(id),
  rg         varchar(255) not null,
  cpf        varchar(255) not null,
  nome       varchar(255) not null,
  endereco   varchar(255) not null,
  profissao  varchar(255)
);

create table rendimentos (
  id                   bigint generated by default as identity primary key,
  cliente_id           bigint not null references clientes(id) on delete cascade,
  entidade_empregadora varchar(255),
  valor                numeric(38,2)
);

create table automoveis (
  id        bigint generated by default as identity primary key,
  matricula varchar(255),
  ano       integer,
  marca     varchar(255),
  modelo    varchar(255),
  placa     varchar(255) unique
);

create table pedidos (
  id                 bigint generated by default as identity primary key,
  cliente_id         bigint references clientes(id),
  automovel_id       bigint references automoveis(id),
  data_inicio        date,
  data_fim           date,
  status             varchar(20) not null default 'PENDENTE'
                     check (status in ('PENDENTE','APROVADO','REPROVADO','CANCELADO','CONTRATADO')),
  parecer_financeiro varchar(255)
);

create table contratos (
  id              bigint generated by default as identity primary key,
  pedido_id       bigint unique references pedidos(id),
  propriedade     varchar(20) check (propriedade in ('CLIENTE','EMPRESA','BANCO')),
  banco_credor_id bigint references usuarios(id),
  valor_credito   numeric(38,2),
  agente_id       bigint references usuarios(id)
);

-- Limite de 3 rendimentos por cliente
create function limita_rendimentos() returns trigger as $$
begin
  if (select count(*) from rendimentos where cliente_id = new.cliente_id) >= 3 then
    raise exception 'máximo de 3 rendimentos por cliente';
  end if;
  return new;
end $$ language plpgsql;

create trigger trg_limita_rendimentos
before insert on rendimentos
for each row execute function limita_rendimentos();

-- Bloqueia o acesso pela API pública do Supabase (o back-end usa conexão direta)
alter table usuarios    enable row level security;
alter table clientes    enable row level security;
alter table rendimentos enable row level security;
alter table automoveis  enable row level security;
alter table pedidos     enable row level security;
alter table contratos   enable row level security;

